#!/usr/bin/env node
/* =============================================================================
   Train the fit-region model from reviewed curves (run once, by the maintainer).

       node web-alpha/ml/train.js data/*.ivtrain
       node web-alpha/ml/train.js --synthetic 200          (pipeline demo only)

   Writes
     web-alpha/model/regions-model.js      the model shipped with the app
     web-alpha/model/training-report.md    how it was validated
   Use --out <folder> to write somewhere else (e.g. to inspect first).
   Nothing to install: Node 18 or newer.
   ============================================================================= */
"use strict";
const fs = require("node:fs");
const path = require("node:path");
const ML = require(path.join(__dirname, "../js/ml.js"));

function usage(msg) {
  if (msg) console.error(`Error: ${msg}\n`);
  console.error("Usage: node web-alpha/ml/train.js <file.ivtrain> [more files…] [--out <folder>] [--note \"text\"]");
  console.error("       node web-alpha/ml/train.js --synthetic <count>     (demo with simulated reviewer)");
  process.exit(msg ? 1 : 0);
}

const args = process.argv.slice(2);
if (!args.length || args.includes("--help")) usage();
const opt = (name) => { const i = args.indexOf(name); if (i < 0) return null; const v = args[i + 1]; args.splice(i, 2); return v; };
const outDir = path.resolve(opt("--out") || path.join(__dirname, "../model"));
const synthetic = opt("--synthetic");
let note = opt("--note") || "";

// ----- load samples -----------------------------------------------------------
let samples = [];
const sources = [];
if (synthetic) {
  samples = require(path.join(__dirname, "synthetic.js")).samples(parseInt(synthetic, 10), 1000);
  sources.push(`synthetic (${samples.length} curves, simulated reviewer)`);
  note = note || "DEMO model trained on synthetic curves with a simulated reviewer — not for real measurements.";
} else {
  for (const file of args) {
    let data;
    try { data = JSON.parse(fs.readFileSync(file, "utf8")); } catch (e) { usage(`${file}: ${e.message}`); }
    if (!data || data.format !== "ivcurve-training-set") usage(`${file} is not a training set (.ivtrain) exported by the app.`);
    samples.push(...data.samples);
    sources.push(`${path.basename(file)} (${data.samples.length} curves, exported ${data.exported_at})`);
  }
}
// the same curve exported twice counts once
const byId = new Map(samples.map((s) => [s.id, s]));
samples = [...byId.values()];
console.log(`Training on ${samples.length} reviewed curves from ${sources.length} source(s)…`);

// ----- train ---------------------------------------------------------------------
let model;
try { model = ML.train(samples, { note }); } catch (e) { usage(e.message); }
model.sources = sources;
const v = model.validation;

// ----- write model + report --------------------------------------------------------
fs.mkdirSync(outDir, { recursive: true });
const js = `/* Fit-region model for the IV Analyser (pre-alpha).
   Generated by web-alpha/ml/train.js on ${model.created} — do not edit by hand.
   Trained on ${model.trained_on} reviewed curves. ${model.note} */
(function (root) {
  "use strict";
  const model = ${JSON.stringify(model)};
  if (root.IV) root.IV.REGION_MODEL = model;
  if (typeof module !== "undefined" && module.exports) module.exports = model;
})(typeof window !== "undefined" ? window : globalThis);
`;
fs.writeFileSync(path.join(outDir, "regions-model.js"), js);

const fmt = (x, d = 2) => (Number.isFinite(x) ? x.toFixed(d) : "—");
const report = [
  "# Fit-region model — training report",
  "",
  `- Created: ${model.created}`,
  model.note ? `- Note: ${model.note}` : null,
  `- Reviewed curves used: **${model.trained_on}** (skipped: ${model.skipped})`,
  `- Sources: ${sources.join("; ")}`,
  `- Ridge regression, λ = ${v.lambda} (chosen by ${v.folds}-fold cross-validation)`,
  `- Boundaries corrected by the model: ${v.corrected.length ? v.corrected.join(", ") : "none (the rules were as good)"}`,
  "",
  "## Held-out curves (cross-validation)",
  "",
  "Mean absolute distance of each boundary to where the reviewers put it:",
  "",
  "| Boundary | Rules (V) | Model (V) |",
  "|---|---|---|",
  ...v.boundaries.map((b) => `| ${b.name} | ${fmt(b.rules_mae_V)} | ${fmt(b.model_mae_V)} |`),
  "",
  "Resulting plasma parameters compared with the reviewers' results (median):",
  "",
  "| | Rules | Model |",
  "|---|---|---|",
  `| Te error (%) | ${fmt(v.te_error_pct.rules_median)} | ${fmt(v.te_error_pct.model_median)} |`,
  `| Vp error (V) | ${fmt(v.vp_error_V.rules_median)} | ${fmt(v.vp_error_V.model_median)} |`,
  `| Curves where the model's regions could not be fitted | — | ${v.model_failed} of ${v.n} |`,
  "",
  "Ship the model only if it is clearly better than the rules on the held-out curves.",
  "",
].filter((l) => l !== null).join("\n");
fs.writeFileSync(path.join(outDir, "training-report.md"), report);

console.log(report);
console.log(`\nWrote ${path.join(outDir, "regions-model.js")} and training-report.md`);
