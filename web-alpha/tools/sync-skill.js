#!/usr/bin/env node
/* =============================================================================
   Writes js/agent-skill.js (the AI agent's built-in skill) from
   skills/langmuir-probe-analysis/SKILL.md. Run after editing the skill:

       node web-alpha/tools/sync-skill.js

   The skill is shipped as a script, not as a .md file: GitHub Pages turns
   Markdown files with a front-matter header into HTML pages, so a SKILL.md
   next to the app cannot be fetched there.
   ============================================================================= */
"use strict";
const fs = require("node:fs");
const path = require("node:path");

const source = path.join(__dirname, "..", "..", "skills", "langmuir-probe-analysis", "SKILL.md");
const target = path.join(__dirname, "..", "js", "agent-skill.js");

function build(text) {
  return `/* Built-in skill of the AI analysis agent — generated by web-alpha/tools/sync-skill.js
   from skills/langmuir-probe-analysis/SKILL.md; edit that file, not this one. */
(function (root) {
  "use strict";
  const skill = { name: "langmuir-probe-analysis (built-in)", text: ${JSON.stringify(text)} };
  if (root.IV) root.IV.AGENT_SKILL = skill;
  if (typeof module !== "undefined" && module.exports) module.exports = skill;
})(typeof window !== "undefined" ? window : globalThis);
`;
}

if (require.main === module) {
  fs.writeFileSync(target, build(fs.readFileSync(source, "utf8")));
  console.log(`Wrote ${path.relative(process.cwd(), target)}`);
}
module.exports = { build, source, target };
